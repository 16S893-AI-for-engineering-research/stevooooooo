def tube_mesh_at_offset(
    tube_nominal_transform_mm: np.ndarray,
    axial_offset_mm: float,
    vendor_dir: Optional[Path] = None,
) -> Optional[object]:
    """Return a trimesh cylinder approximating the tube at a given axial offset.

    The tube has OD ≈ 8*10 mm, height ≈ 81 mm (from collision report, Part 13).
    ``axial_offset_mm`` shifts the tube along STEP +Y.

    Parameters
    ----------
    tube_nominal_transform_mm : 4×4 world transform for the tube at offset=0
    axial_offset_mm : shift along +Y in STEP world frame
    """
    try:
        import trimesh
    except ImportError:
        return None

    # Create a cylinder: OD = 2*40 mm, height 81 mm, centred at origin
    # (tube OD ~8*10 mm from collision report bbox X-span)
    _TUBE_RADIUS_MM = 4 * 10  # 40 mm
    cyl = trimesh.creation.cylinder(radius=_TUBE_RADIUS_MM, height=81.0, sections=32)

    T = tube_nominal_transform_mm.copy()
    T[1, 3] += axial_offset_mm  # shift in STEP +Y

    cyl.apply_transform(T)
    return cyl
