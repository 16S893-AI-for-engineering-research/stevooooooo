def rpy_to_matrix(r: float, p: float, y: float) -> np.ndarray:
    cr, sr = math.cos(r), math.sin(r)
    cp, sp = math.cos(p), math.sin(p)
    cy, sy = math.cos(y), math.sin(y)
    Rx = np.array([[1, 0, 0], [0, cr, -sr], [0, sr, cr]])
    Ry = np.array([[cp, 0, sp], [0, 1, 0], [-sp, 0, cp]])
    Rz = np.array([[cy, -sy, 0], [sy, cy, 0], [0, 0, 1]])
    return Rz @ Ry @ Rx


def make_tf(xyz_m: np.ndarray, rpy: Tuple[float, float, float]) -> np.ndarray:
    T = np.eye(4)
    T[:3, :3] = rpy_to_matrix(*rpy)
    T[:3, 3] = xyz_m
    return T


@dataclass
class ArmMeshSet:
    """Trimesh meshes for one arm, in STEP world frame (mm)."""
    arm_side: str   # 'left' or 'right'
    link_meshes: Dict[str, object]  # link_name -> trimesh.Trimesh (in world, mm)


def load_arm_meshes(
    T_world_base_mm: np.ndarray,
    q: List[float],
    vendor_dir: Path,
    arm_side: str,
) -> ArmMeshSet:
    """Load SO-101 arm link meshes, apply FK, and return in STEP world frame (mm).

    Parameters
    ----------
    T_world_base_mm : 4×4 with translation in mm
    q : 5 joint angles [shoulder_pan, shoulder_lift, elbow_flex, wrist_flex, wrist_roll]
    vendor_dir : robot/vendor/so101/
    arm_side : 'left' or 'right'
    """
    import trimesh
    from .arm_placer import forward_kinematics, JOINT_NAMES

    # Convert mm transform to metres for FK
    T_world_base_m = T_world_base_mm.copy()
    T_world_base_m[:3, 3] /= 1000.0

    frames = forward_kinematics(T_world_base_m, q)

    assets = vendor_dir / "assets"
    result = {}

    for link_name, visuals in _LINK_VISUAL_MESHES.items():
        T_world_link = frames.get(link_name)
        if T_world_link is None:
            continue

        meshes_in_world = []
        for fname, xyz_m, rpy in visuals:
            stl_path = assets / fname
            if not stl_path.exists():
                continue
            mesh = trimesh.load(str(stl_path))
            # Transform: world ← link ← visual_origin ← mesh_vertices
            T_vis = make_tf(np.array(xyz_m), rpy)
            T_world_vis_m = T_world_link @ T_vis
            # Scale to mm
            T_world_vis_mm = T_world_vis_m.copy()
            T_world_vis_mm[:3, 3] *= 1000.0
            # Also scale the mesh vertices (STL is in metres)
            mc = mesh.copy()
            mc.apply_transform(T_world_vis_mm)
            mc.apply_scale(1000.0)  # m -> mm
            # Actually apply_transform already put it in mm coordinates because translation is in mm
            # and vertices are in m, so this would double-scale. Correct approach:
            # First scale the mesh to mm, then apply transform
            mc2 = mesh.copy()
            mc2.apply_scale(1000.0)  # vertices: m -> mm
            T_world_vis_mm2 = T_world_vis_m.copy()
            T_world_vis_mm2[:3, 3] *= 1000.0
            mc2.apply_transform(T_world_vis_mm2)
            meshes_in_world.append(mc2)

        if meshes_in_world:
            combined = trimesh.util.concatenate(meshes_in_world)
            result[link_name] = combined

    return ArmMeshSet(arm_side=arm_side, link_meshes=result)


