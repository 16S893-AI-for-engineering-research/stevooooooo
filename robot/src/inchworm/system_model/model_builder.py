@dataclass
class PartRecord:
    """Metadata for one STEP part instance."""
    instance_id: str
    nauo_id: str
    name: str
    group: str
    origin_mm: List[float]  # (x, y, z) mm in STEP world frame


def build_part_classification(
    step_path: Path,
) -> Tuple[List[PartRecord], Dict[str, int]]:
    """Parse STEP placements and classify all parts.

    Returns
    -------
    records : list of PartRecord
    counts : {group: count}
    """
    from .step_parser import parse_step_placements

    placements = parse_step_placements(step_path)
    records = []

    for p in placements:
        group = classify_part(p.component_name, p.origin_mm)
        records.append(PartRecord(
            instance_id=p.instance_id,
            nauo_id=p.nauo_id,
            name=p.component_name,
            group=group,
            origin_mm=p.origin_mm.tolist(),
        ))

    counts: Dict[str, int] = {}
    for r in records:
        counts[r.group] = counts.get(r.group, 0) + 1

    return records, counts


def save_classification_yaml(records: List[PartRecord], out_path: Path) -> None:
    """Save part classification to YAML (committed; small file)."""
    import yaml

    # Build YAML content
    groups: Dict[str, List[dict]] = {}
    for r in records:
        if r.group not in groups:
            groups[r.group] = []
        groups[r.group].append({
            "name": r.name,
            "nauo_id": r.nauo_id,
            "origin_mm": [round(v, 2) for v in r.origin_mm],
        })

    doc = {
        "# source": "Generated by robot/src/inchworm/system_model/model_builder.py",
        "# step_file": "CAD/Assembly 1.step",
        "# description": (
            "Part classification for the inchworm robot STEP assembly. "
            "Groups: arm_left, arm_right, tube, dexarm, chassis, other."
        ),
        "counts": {g: len(v) for g, v in groups.items()},
        "parts": groups,
    }

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as fh:
        yaml.dump(doc, fh, default_flow_style=False, allow_unicode=True, sort_keys=False)


