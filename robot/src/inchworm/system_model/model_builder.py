"""
model_builder.py
================
Builds the full-system geometric model:
1. Classifies all STEP placement instances into groups.
2. Loads arm meshes from the vendored URDF STL assets.
3. Provides functions to tessellate non-arm parts via OCP (optional fallback to
   bbox-only when OCP tessellation crashes).
4. Saves a part classification YAML to robot/config/system_model_parts.yaml.

Part groups
-----------
- arm_left   : SO-101 arm parts with lower STEP Y (~204 mm)
- arm_right  : SO-101 arm parts with higher STEP Y (~386 mm)
- tube       : Part 13 (three inchworm-state instances)
- dexarm     : Large Part N bodies in STEP Y < 0 region
- chassis    : Large Part N bodies in the positive-Y region
- other      : Remaining parts (screws, PCB components, etc.)
"""
from __future__ import annotations

import json
import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np

# ---------------------------------------------------------------------------
# Part classification
# ---------------------------------------------------------------------------

# Y threshold (mm) to separate left/right arms
_ARM_LEFT_Y_MAX = 300.0   # left arm base Y ≈ 204 mm
_ARM_RIGHT_Y_MIN = 300.0  # right arm base Y ≈ 386 mm

# Y threshold to separate DexArm region
_DEXARM_Y_MAX = 50.0   # DexArm parts have Y < 50 mm

# SO-101 structural part names (substrings)
_SO101_NAMES = (
    "Base_SO101",
    "Rotation_Pitch_SO101",
    "Motor_holder_SO101",
    "Upper_arm_SO101",
    "Under_arm_SO101",
    "Wrist_Roll_Pitch_SO100",
    "WaveShare_Mounting_Plate_SO101",
    "Base_08p",
    "Board",
    "GE_",
    "SG-ZIJI",
    "XG-ZIJI",
    "ZK_",
    "PCB-CHAZUO",
    "MOTOR-1723",
)

# Part names that are TUBE (Part 13)
_TUBE_NAME = "Part 13"

# Parts names that are chassis frame (positive-Y, non-arm, non-tube)
_CHASSIS_NAMES = (
    "Extruded",
    "Component",
    "Composant",
    "Corps",
)


def classify_part(name: str, origin_mm: np.ndarray) -> str:
    """Classify a STEP part by name and Y position.

    Returns one of: arm_left, arm_right, tube, dexarm, chassis, other.
    """
    # Tube: Part 13
    base_name = name.split(":")[0].split("__")[0].strip()
    if base_name == _TUBE_NAME:
        return "tube"

    # SO-101 arm parts: classify by Y
    is_arm = any(kw in name for kw in _SO101_NAMES)
    if is_arm:
        y = origin_mm[1]
        if y < _ARM_LEFT_Y_MAX:
            return "arm_left"
        else:
            return "arm_right"

    # DexArm region: Y < 50 mm
    y = origin_mm[1]
    if y < _DEXARM_Y_MAX:
        return "dexarm"

    # Chassis and other structural parts
    for kw in _CHASSIS_NAMES:
        if kw in name:
            return "chassis"

    return "other"


